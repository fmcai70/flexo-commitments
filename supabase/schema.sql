-- The app's address, used in emails. Change it when the app moves (e.g. to Hostinger) and re-run.
create or replace function public.ar_app_url() returns text language sql immutable as $$
  select 'https://fmcai70.github.io/flexo-commitments/'
$$;

create or replace function public.ar_err(p_code text, p_msg text) returns void language plpgsql as $$
begin
  raise exception '%', p_msg using errcode = p_code;  -- AR400 bad input, AR403 not allowed, AR404 gone, AR409 stale
end $$;

create or replace function public.ar_str(p jsonb, k text) returns text language sql immutable as $$
  select case when jsonb_typeof(p -> k) = 'string' then p ->> k else '' end
$$;

create or replace function public.ar_arr(p jsonb) returns jsonb language sql immutable as $$
  select case when jsonb_typeof(p) = 'array' then p else '[]'::jsonb end
$$;

create or replace function public.ar_try_date(s text) returns date language plpgsql immutable as $$
begin
  if s ~ '^\d{4}-\d{2}-\d{2}' then return left(s, 10)::date; end if;
  return null;
exception when others then return null;
end $$;

-- 'done', 'prog', 'none' etc., as the app computes it.
create or replace function public.ar_status(p jsonb) returns text language sql immutable as $$
  select case
    when jsonb_typeof(p -> 'progress') = 'object' then
      case when p -> 'done' = 'true'::jsonb or public.ar_str(p -> 'progress', 'status') = 'done' then 'done'
           else public.ar_str(p -> 'progress', 'status') end
    when p -> 'done' = 'true'::jsonb then 'done'
    when jsonb_array_length(public.ar_arr(p -> 'activities')) > 0
         and not exists (select 1 from jsonb_array_elements(public.ar_arr(p -> 'activities')) a
                         where public.ar_str(a, 'status') <> 'done') then 'done'
    when exists (select 1 from jsonb_array_elements(public.ar_arr(p -> 'activities')) a
                 where public.ar_str(a, 'status') <> 'todo') then 'prog'
    else 'none' end
$$;

create or replace function public.ar_is_helper(p jsonb, p_name text) returns boolean language sql immutable as $$
  select public.ar_arr(p -> 'coResp') ? p_name
      or exists (select 1 from jsonb_array_elements(public.ar_arr(p -> 'activities')) a
                 where public.ar_arr(a -> 'helpers') ? p_name or public.ar_str(a, 'helper') = p_name)
$$;

-- The signed-in person's own place on the list (matched by account, or by email before first use).
create or replace function public.ar_own_member() returns public.ar_members
language sql stable security definer set search_path = public as $$
  select m.* from public.ar_members m
  where m.user_id = auth.uid()
     or (m.user_id is null and m.email is not null
         and lower(m.email) = (select lower(email) from public.profiles where id = auth.uid()))
  order by (m.user_id = auth.uid()) desc nulls last
  limit 1
$$;

create or replace function public.ar_is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select public.is_admin()
      or coalesce((select m.is_active and m.is_admin from public.ar_own_member() m where m.id is not null), false)
$$;

-- May the signed-in person use ActionRegister at all?
create or replace function public.ar_allowed() returns boolean
language sql stable security definer set search_path = public as $$
  select public.has_app_access('actionregister')
     and (public.ar_is_admin()
          or coalesce((select m.is_active from public.ar_own_member() m where m.id is not null), false))
$$;

-- Who the change is made as: the person themself, or (admins only) the person chosen in "Viewing as".
create or replace function public.ar_actor(p_as text) returns public.ar_members
language plpgsql stable security definer set search_path = public as $$
declare
  own public.ar_members := public.ar_own_member();
  act public.ar_members;
begin
  if not public.ar_allowed() then
    perform public.ar_err('AR403', 'You are not on the ActionRegister list. Ask an administrator to add you.');
  end if;
  if coalesce(p_as, '') = '' or (own.id is not null and own.is_active and p_as = own.display_name) then
    if own.id is null or not own.is_active then
      perform public.ar_err('AR400', 'Choose who you are viewing as first.');
    end if;
    return own;
  end if;
  if not public.ar_is_admin() then
    perform public.ar_err('AR403', 'Only an administrator can work as someone else.');
  end if;
  select * into act from public.ar_members where display_name = p_as and is_active;
  if act.id is null then perform public.ar_err('AR400', '''' || p_as || ''' is not on the ActionRegister list.'); end if;
  return act;
end $$;

create or replace function public.ar_audit(p_type text, p_id text, p_action text, p_actor public.ar_members, p_details text)
returns void language sql security definer set search_path = public as $$
  insert into public.ar_audit_log (entity_type, entity_id, action, performed_by, acting_as, details)
  values (p_type, p_id, p_action, auth.uid(),
          case when p_actor.id is distinct from (select m.id from public.ar_own_member() m) then p_actor.display_name end,
          left(p_details, 1000));
$$;

-- Queue an email to people on the list (by display name), skipping anyone without an email address.
create or replace function public.ar_mail(p_names text[], p_subject text, p_body text)
returns void language sql security definer set search_path = public as $$
  insert into public.ar_outbox (to_email, subject, body)
  select distinct lower(m.email), '[ActionRegister] ' || p_subject, p_body
  from public.ar_members m
  where m.is_active and m.display_name = any (p_names) and coalesce(m.email, '') <> ''
$$;

create or replace function public.ar_short(t text) returns text language sql immutable as $$
  select case when length(t) <= 70 then t else left(t, 68) || '…' end
$$;

-- ---------------------------------------------------------------------
-- Loading everything ("state"), with a cheap "has anything changed?" stamp for the 10-second refresh
-- ---------------------------------------------------------------------
create or replace function public.ar_stamp() returns text
language sql stable security definer set search_path = public as $$
  select concat_ws('-',
    (select count(*) || '.' || coalesce(extract(epoch from max(updated_at))::text, '') from public.ar_projects),
    (select count(*) || '.' || coalesce(extract(epoch from max(updated_at))::text, '') from public.ar_subplans),
    (select count(*) || '.' || coalesce(extract(epoch from max(updated_at))::text, '') from public.ar_members))
$$;

-- Who am I? Used at sign-in, before the app loads.
create or replace function public.ar_whoami() returns jsonb
language plpgsql volatile security definer set search_path = public as $$
declare own public.ar_members := public.ar_own_member();
begin
  -- Remember the account on first use, so a later email change doesn't lose the link.
  if own.id is not null and own.user_id is null then
    update public.ar_members set user_id = auth.uid() where id = own.id;
  end if;
  return jsonb_build_object(
    'allowed', public.ar_allowed(),
    'appAccess', public.has_app_access('actionregister'),
    'me', case when own.is_active then own.display_name end,
    'isAdmin', public.ar_is_admin(),
    'canSwitch', public.ar_is_admin());
end $$;

create or replace function public.ar_state(p_stamp text default null) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare
  st text := public.ar_stamp();
  own public.ar_members := public.ar_own_member();
begin
  if not public.ar_allowed() then
    perform public.ar_err('AR403', 'You are not on the ActionRegister list. Ask an administrator to add you.');
  end if;
  if p_stamp = st then return jsonb_build_object('unchanged', true, 'stamp', st); end if;
  return jsonb_build_object(
    'stamp', st,
    'me', case when own.is_active then own.display_name end,
    'isAdmin', public.ar_is_admin(),
    'execs', coalesce((select jsonb_agg(display_name order by sort_order, display_name) from public.ar_members
                       where is_active and role = 'exec'), '[]'),
    'managers', coalesce((select jsonb_agg(jsonb_build_object('name', display_name, 'dept', coalesce(department, ''))
                          order by sort_order, display_name) from public.ar_members where is_active and role = 'manager'), '[]'),
    'seesAllFiles', coalesce((select jsonb_agg(display_name) from public.ar_members where is_active and sees_all_files), '[]'),
    'projects', coalesce((select jsonb_agg(p.doc || jsonb_build_object('id', p.id, '_v', p.version::text)) from public.ar_projects p), '[]'),
    'subplans', coalesce((select jsonb_object_agg(s.project_id, s.doc || jsonb_build_object('_v', s.version::text)) from public.ar_subplans s), '{}'));
end $$;

-- ---------------------------------------------------------------------
-- Projects
-- ---------------------------------------------------------------------
create or replace function public.ar_put_project(p_id text, p_body jsonb, p_base text default null, p_as text default null)
returns jsonb language plpgsql volatile security definer set search_path = public as $$
declare
  me public.ar_members := public.ar_actor(p_as);
  ex public.ar_projects;
  body jsonb := coalesce(p_body, '{}'::jsonb) - 'id' - '_v';
  v_owner text := public.ar_str(body, 'owner');
  k text;
  before_ext jsonb; after_ext jsonb; b_status text; a_status text;
  approvers text[];
  link text := public.ar_app_url();
  title text := public.ar_str(body, 'title');
  new_version bigint;
begin
  if p_id is null or p_id !~ '^[A-Za-z0-9_-]{1,64}$' then perform public.ar_err('AR400', 'Bad project id.'); end if;
  if jsonb_typeof(body) <> 'object' then perform public.ar_err('AR400', 'Bad project.'); end if;
  select * into ex from public.ar_projects where id = p_id for update;

  -- CommitmentRules.CheckProjectWrite
  if me.role <> 'exec' then
    if ex.id is null then
      if v_owner <> me.display_name and public.ar_str(body, 'assignedBy') <> me.display_name then
        perform public.ar_err('AR403', 'You can add projects for yourself, or assign one to a co-manager under your own name.');
      end if;
    elsif v_owner <> public.ar_str(ex.doc, 'owner') then
      perform public.ar_err('AR403', 'The owner of a project can''t be changed.');
    elsif public.ar_str(ex.doc, 'owner') = me.display_name or public.ar_str(ex.doc, 'assignedBy') = me.display_name then
      null;
    elsif public.ar_is_helper(ex.doc, me.display_name) then
      for k in select jsonb_object_keys(ex.doc) union select jsonb_object_keys(body) loop
        if k not in ('helperInputs', 'activities', 'updatedAt', 'updatedBy', 'id', '_v')
           and (ex.doc -> k) is distinct from (body -> k) then
          perform public.ar_err('AR403', 'As a helper you can only update your activities and send your input to the owner.');
        end if;
      end loop;
    else
      perform public.ar_err('AR403', 'Only the owner can change this project.');
    end if;
  end if;
  if not exists (select 1 from public.ar_members where display_name = v_owner and is_active) then
    perform public.ar_err('AR400', '''' || v_owner || ''' is not on the ActionRegister list.');
  end if;
  if ex.id is not null and (p_base is null or p_base <> ex.version::text) then
    perform public.ar_err('AR409', 'stale');
  end if;

  body := body || jsonb_build_object('updatedAt', to_char(now() at time zone 'utc', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),
                                     'updatedBy', me.display_name);
  if ex.id is null then
    insert into public.ar_projects (id, owner, assigned_by, plan, commit_date, done, doc, updated_by)
    values (p_id, v_owner, nullif(left(public.ar_str(body, 'assignedBy'), 100), ''), nullif(left(public.ar_str(body, 'plan'), 8), ''),
            nullif(left(public.ar_str(body, 'commitDate'), 10), ''), public.ar_status(body) = 'done', body, me.display_name)
    returning version into new_version;
    perform public.ar_audit('Project', p_id, 'Created', me, title);
  else
    update public.ar_projects set owner = v_owner, assigned_by = nullif(left(public.ar_str(body, 'assignedBy'), 100), ''),
      plan = nullif(left(public.ar_str(body, 'plan'), 8), ''), commit_date = nullif(left(public.ar_str(body, 'commitDate'), 10), ''),
      done = public.ar_status(body) = 'done', doc = body, version = version + 1, updated_at = now(), updated_by = me.display_name
    where id = p_id returning version into new_version;
    perform public.ar_audit('Project', p_id, 'Updated', me, 'changed: ' || coalesce((
      select string_agg(k2, ', ') from (select jsonb_object_keys(ex.doc) k2 union select jsonb_object_keys(body)) ks
      where k2 not in ('updatedAt', 'updatedBy') and (ex.doc -> k2) is distinct from (body -> k2)), ''));
  end if;

  -- Emails (CommitmentNotifier)
  if ex.id is null and v_owner <> me.display_name then
    perform public.ar_mail(array[v_owner], 'New commitment assigned to you: ' || public.ar_short(title),
      me.display_name || ' assigned you a project in ActionRegister:' || E'\n\n' || title || E'\n'
      || case when public.ar_str(body, 'commitDate') <> '' then 'Deadline: ' || public.ar_str(body, 'commitDate') || E'\n' else '' end
      || case when public.ar_str(body, 'brief') <> '' then E'\nInstructions: ' || public.ar_str(body, 'brief') || E'\n' else '' end
      || E'\nOpen it here: ' || link);
  end if;
  before_ext := ex.doc -> 'extension'; after_ext := body -> 'extension';
  if jsonb_typeof(after_ext) = 'object' then
    b_status := public.ar_str(before_ext, 'status'); a_status := public.ar_str(after_ext, 'status');
    if a_status = 'pending' and (b_status <> 'pending'
        or public.ar_str(before_ext, 'requestedAt') <> public.ar_str(after_ext, 'requestedAt')
        or public.ar_str(before_ext, 'requested') <> public.ar_str(after_ext, 'requested')) then
      if public.ar_str(body, 'plan') = 'CM' then approvers := array[public.ar_str(body, 'assignedBy')];
      else select array_agg(display_name) into approvers from public.ar_members where is_active and role = 'exec'; end if;
      perform public.ar_mail(array_remove(approvers, v_owner), 'Extension request: ' || public.ar_short(title),
        v_owner || ' asked to move the deadline of:' || E'\n\n' || title || E'\n\n'
        || 'From ' || public.ar_str(after_ext, 'forDeadline') || ' to ' || public.ar_str(after_ext, 'requested') || E'\n'
        || 'Reason: ' || public.ar_str(after_ext, 'reason') || E'\n\nApprove or decline it here: ' || link);
    end if;
    if b_status = 'pending' and a_status in ('approved', 'declined') then
      perform public.ar_mail(array[v_owner], 'Extension ' || a_status || ': ' || public.ar_short(title),
        public.ar_str(after_ext, 'decidedBy') || ' replied to your deadline request for:' || E'\n\n' || title || E'\n\nIt '
        || case when a_status = 'approved' then 'was approved. The new deadline is ' || public.ar_str(after_ext, 'requested') || '.'
                else 'was declined. Please update your progress and check in again.' end || E'\n'
        || case when public.ar_str(after_ext, 'reply') <> '' then E'\nReply: ' || public.ar_str(after_ext, 'reply') || E'\n' else '' end
        || E'\nOpen it here: ' || link);
    end if;
  end if;

  return jsonb_build_object('version', new_version::text, 'updatedAt', body ->> 'updatedAt', 'updatedBy', me.display_name);
end $$;

-- Returns the storage paths of removed attachments; the app then deletes those files from storage.
create or replace function public.ar_delete_project(p_id text, p_as text default null)
returns jsonb language plpgsql volatile security definer set search_path = public as $$
declare
  me public.ar_members := public.ar_actor(p_as);
  t text;
  keys jsonb;
begin
  if me.role <> 'exec' then perform public.ar_err('AR403', 'Only an executive can delete a project.'); end if;
  select public.ar_str(doc, 'title') into t from public.ar_projects where id = p_id;
  if not found then return '[]'::jsonb; end if;
  with gone as (delete from public.ar_files where parent_id = p_id and kind in ('p', 's') returning storage_key)
  select coalesce(jsonb_agg(storage_key), '[]') into keys from gone;
  delete from public.ar_projects where id = p_id;   -- its sub plan goes with it
  perform public.ar_audit('Project', p_id, 'Deleted', me, t);
  return keys;
end $$;

-- ---------------------------------------------------------------------
-- Sub plans
-- ---------------------------------------------------------------------
create or replace function public.ar_put_subplan(p_id text, p_body jsonb, p_base text default null, p_as text default null)
returns jsonb language plpgsql volatile security definer set search_path = public as $$
declare
  me public.ar_members := public.ar_actor(p_as);
  proj public.ar_projects;
  ex public.ar_subplans;
  body jsonb := coalesce(p_body, '{}'::jsonb) - '_v';
  v_assignee text := public.ar_str(body, 'assignee');
  new_version bigint;
begin
  select * into proj from public.ar_projects where id = p_id;
  if proj.id is null then perform public.ar_err('AR404', 'That project no longer exists.'); end if;
  select * into ex from public.ar_subplans where project_id = p_id for update;
  if me.role <> 'exec' then
    if ex.project_id is null then
      if proj.owner <> me.display_name then perform public.ar_err('AR403', 'Only the project owner can create its sub plan.'); end if;
    elsif public.ar_str(ex.doc, 'owner') <> me.display_name and public.ar_str(ex.doc, 'assignee') <> me.display_name then
      perform public.ar_err('AR403', 'Only the owner and the assigned manager can edit this sub plan.');
    end if;
  end if;
  if not exists (select 1 from public.ar_members where display_name = v_assignee and is_active) then
    perform public.ar_err('AR400', '''' || v_assignee || ''' is not on the ActionRegister list.');
  end if;
  if ex.project_id is not null and (p_base is null or p_base <> ex.version::text) then
    perform public.ar_err('AR409', 'stale');
  end if;
  body := body || jsonb_build_object('updatedAt', to_char(now() at time zone 'utc', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),
                                     'updatedBy', me.display_name);
  if ex.project_id is null then
    insert into public.ar_subplans (project_id, owner, assignee, doc, updated_by)
    values (p_id, proj.owner, v_assignee, body, me.display_name) returning version into new_version;
    perform public.ar_audit('Subplan', p_id, 'Created', me, public.ar_str(body, 'title'));
  else
    update public.ar_subplans set owner = proj.owner, assignee = v_assignee, doc = body,
      version = version + 1, updated_at = now(), updated_by = me.display_name
    where project_id = p_id returning version into new_version;
    perform public.ar_audit('Subplan', p_id, 'Updated', me, null);
  end if;
  return jsonb_build_object('version', new_version::text, 'updatedAt', body ->> 'updatedAt', 'updatedBy', me.display_name);
end $$;

create or replace function public.ar_delete_subplan(p_id text, p_as text default null)
returns jsonb language plpgsql volatile security definer set search_path = public as $$
declare
  me public.ar_members := public.ar_actor(p_as);
  row_owner text;
  keys jsonb;
begin
  select owner into row_owner from public.ar_subplans where project_id = p_id;
  if not found then return '[]'::jsonb; end if;
  if me.role <> 'exec' and row_owner <> me.display_name then
    perform public.ar_err('AR403', 'Only the project owner can delete its sub plan.');
  end if;
  with gone as (delete from public.ar_files where parent_id = p_id and kind = 's' returning storage_key)
