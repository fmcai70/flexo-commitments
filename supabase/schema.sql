-- ---------------------------------------------------------------------
-- Daily reminders (ReminderService): check-ins due within a week and sub plan updates due
-- ---------------------------------------------------------------------
create or replace function public.ar_subplan_cycle(p_schedule text, p_created text, p_today date) returns date
language plpgsql immutable as $$
declare c date;
begin
  if p_schedule = 'weekly-thu' then
    c := p_today - ((extract(dow from p_today)::int - 4 + 7) % 7);
  elsif p_schedule = 'first-thu' then
    c := date_trunc('month', p_today)::date;
    c := c + ((4 - extract(dow from c)::int + 7) % 7);
    if c > p_today then
      c := (date_trunc('month', p_today) - interval '1 month')::date;
      c := c + ((4 - extract(dow from c)::int + 7) % 7);
    end if;
  else
    return null;
  end if;
  if to_char(c, 'YYYY-MM-DD') collate "C" <= coalesce(nullif(p_created, ''), '0000-00-00') collate "C" then return null; end if;
  return c;
end $$;

create or replace function public.ar_daily_reminders(p_today date default (now() at time zone 'Asia/Manila')::date)
returns int language plpgsql volatile security definer set search_path = public as $$
declare
  link text := public.ar_app_url();
  r record;
  sent int := 0;
begin
  create temp table if not exists ar_due (who text, kind text, key text, line text) on commit drop;
  delete from ar_due;

  insert into ar_due
  select p.owner, 'checkin', 'checkin|' || p.id || '|' || public.ar_str(p.doc, 'commitDate'),
         '- ' || public.ar_str(p.doc, 'title') || ' (' ||
         case when d < p_today then 'overdue since ' || public.ar_str(p.doc, 'commitDate')
              when d = p_today then 'due today' else 'due ' || public.ar_str(p.doc, 'commitDate') end || ')'
  from public.ar_projects p, lateral (select public.ar_try_date(public.ar_str(p.doc, 'commitDate')) d) x
  where not p.done and public.ar_status(p.doc) <> 'done'
    and public.ar_str(p.doc -> 'extension', 'status') <> 'pending'
    and d is not null and d - p_today <= 7
    and public.ar_str(p.doc -> 'checkin', 'forDeadline') <> public.ar_str(p.doc, 'commitDate');

  insert into ar_due
  select s.assignee, 'subplan', 'subplan|' || s.project_id || '|' || to_char(c, 'YYYY-MM-DD'),
         '- ' || public.ar_str(s.doc, 'title') || ' (update due since ' || to_char(c, 'YYYY-MM-DD') || ')'
  from public.ar_subplans s,
       lateral (select public.ar_subplan_cycle(public.ar_str(s.doc, 'schedule'), public.ar_str(s.doc, 'createdAt'), p_today) c) x
  where s.doc -> 'complete' is distinct from 'true'::jsonb and c is not null
    and public.ar_str(s.doc, 'lastSubmitted') collate "C" < to_char(c, 'YYYY-MM-DD') collate "C";

  delete from ar_due where key in (select key from public.ar_notification_log);

  for r in
    select d.who, d.kind, m.email, array_agg(d.key) keys, string_agg(d.line, E'\n' order by d.line) lines
    from ar_due d join public.ar_members m on m.display_name = d.who and m.is_active and coalesce(m.email, '') <> ''
    group by d.who, d.kind, m.email
  loop
    insert into public.ar_outbox (to_email, subject, body) values (lower(r.email),
      '[ActionRegister] ' || case when r.kind = 'checkin' then 'Projects waiting for your update' else 'Sub plan update due' end,
      'Hello ' || split_part(r.who, ' ', 1) || E',\n\n'
      || case when r.kind = 'checkin'
              then 'These projects are due within a week (or overdue). Please open ActionRegister and confirm where each one stands, or ask for a new deadline:'
              else 'These sub plan updates are due. Please fill them in and submit your update:' end
      || E'\n\n' || r.lines || E'\n\nOpen it here: ' || link);
    insert into public.ar_notification_log (key) select unnest(r.keys) on conflict do nothing;
    sent := sent + 1;
  end loop;
  return sent;
end $$;

-- Every day at 8:00 Manila time (00:00 UTC), if the Cron integration (pg_cron) is turned on.
do $$
begin
  if exists (select 1 from pg_namespace where nspname = 'cron') then
    perform cron.schedule('ar-daily-reminders', '0 0 * * *', 'select public.ar_daily_reminders()');
  end if;
end $$;

-- ---------------------------------------------------------------------
-- One-time import from the old SQL Server app (migration/export-commitments.ps1 → import.html).
-- Flexo admins only. Refuses if projects already exist, unless p_replace is true.
-- ---------------------------------------------------------------------
create or replace function public.ar_import(p_data jsonb, p_replace boolean default false)
returns jsonb language plpgsql volatile security definer set search_path = public as $$
declare
  r jsonb;
  doc jsonb;
  em text;
  n_members int := 0; n_projects int := 0; n_subplans int := 0; n_files int := 0;
  m record;
  no_account text[] := '{}';
begin
  if not public.is_admin() then perform public.ar_err('AR403', 'Only a Flexo admin can import.'); end if;
  if exists (select 1 from public.ar_projects) and not coalesce(p_replace, false) then
    perform public.ar_err('AR409', 'ActionRegister already has projects. Tick "Replace" to import again.');
  end if;
  if coalesce(p_replace, false) then
    delete from public.ar_files; delete from public.ar_subplans; delete from public.ar_projects;
    delete from public.ar_notification_log;
  end if;

  for r in select * from jsonb_array_elements(public.ar_arr(p_data -> 'members')) loop
    em := nullif(lower(trim(coalesce(r ->> 'email', ''))), '');
    if em like '%@placeholder.local' then em := null; end if;
    insert into public.ar_members (display_name, email, department, role, is_admin, sees_all_files, is_active, sort_order, ad_username)
    values (r ->> 'name', em, nullif(r ->> 'dept', ''), case when r ->> 'role' = 'exec' then 'exec' else 'manager' end,
            coalesce((r ->> 'isAdmin')::boolean, false) or coalesce((r ->> 'employeeIsAdmin')::boolean, false),
            coalesce((r ->> 'seesAllFiles')::boolean, false), coalesce((r ->> 'isActive')::boolean, true),
            coalesce((r ->> 'sortOrder')::int, 0), r ->> 'adUsername')
    on conflict (display_name) do update set email = coalesce(excluded.email, ar_members.email), department = excluded.department,
      role = excluded.role, is_admin = excluded.is_admin, sees_all_files = excluded.sees_all_files,
      is_active = excluded.is_active, sort_order = excluded.sort_order, ad_username = excluded.ad_username, updated_at = now();
    n_members := n_members + 1;
  end loop;

  for r in select * from jsonb_array_elements(public.ar_arr(p_data -> 'projects')) loop
    doc := (r ->> 'json')::jsonb - 'id' - '_v';
    insert into public.ar_projects (id, owner, assigned_by, plan, commit_date, done, doc, updated_at, updated_by)
    values (r ->> 'id', public.ar_str(doc, 'owner'), nullif(left(public.ar_str(doc, 'assignedBy'), 100), ''),
            nullif(left(public.ar_str(doc, 'plan'), 8), ''), nullif(left(public.ar_str(doc, 'commitDate'), 10), ''),
            public.ar_status(doc) = 'done', doc, coalesce((r ->> 'updatedAt')::timestamptz, now()), r ->> 'updatedBy');
    n_projects := n_projects + 1;
  end loop;

  for r in select * from jsonb_array_elements(public.ar_arr(p_data -> 'subplans')) loop
    doc := (r ->> 'json')::jsonb - '_v';
    insert into public.ar_subplans (project_id, owner, assignee, doc, updated_at, updated_by)
    values (r ->> 'projectId', public.ar_str(doc, 'owner'), public.ar_str(doc, 'assignee'), doc,
            coalesce((r ->> 'updatedAt')::timestamptz, now()), r ->> 'updatedBy');
    n_subplans := n_subplans + 1;
  end loop;

  -- Files keep their ids (the projects refer to them); the importing admin uploads them next.
  for r in select * from jsonb_array_elements(public.ar_arr(p_data -> 'files')) loop
    insert into public.ar_files (id, kind, parent_id, file_name, size_bytes, storage_key, uploaded_by, uploaded_by_user, uploaded_at)
    values ((r ->> 'id')::uuid, r ->> 'kind', r ->> 'parentId', r ->> 'fileName', (r ->> 'size')::bigint,
            'legacy/' || replace(r ->> 'storageKey', '\', '/'), r ->> 'uploadedBy', auth.uid(),
            coalesce((r ->> 'uploadedAt')::timestamptz, now()))
    on conflict (id) do update set storage_key = excluded.storage_key, uploaded_by_user = auth.uid();
    n_files := n_files + 1;
  end loop;

  insert into public.ar_audit_log (entity_type, entity_id, action, at, details)
  select a ->> 'entityType', a ->> 'entityId', a ->> 'action', coalesce((a ->> 'at')::timestamptz, now()),
         concat_ws(' ', nullif(a ->> 'details', ''), case when a ->> 'actingAs' <> '' then '(as ' || (a ->> 'actingAs') || ')' end)
  from jsonb_array_elements(public.ar_arr(p_data -> 'audit')) a;
  insert into public.ar_notification_log (key, sent_at)
  select a ->> 'key', coalesce((a ->> 'sentAt')::timestamptz, now()) from jsonb_array_elements(public.ar_arr(p_data -> 'sentReminders')) a
  on conflict do nothing;
  perform public.ar_audit('Project', '*', 'Imported', public.ar_own_member(),
    format('%s projects, %s sub plans, %s files from %s', n_projects, n_subplans, n_files, p_data ->> 'source'));

  for m in select id, display_name, email from public.ar_members where is_active loop
    perform public.ar_grant_access(m.id);
    if not exists (select 1 from public.profiles p where lower(p.email) = lower(m.email)) then
      no_account := no_account || m.display_name;
    end if;
  end loop;

  return jsonb_build_object('members', n_members, 'projects', n_projects, 'subplans', n_subplans, 'files', n_files,
    'noAccount', to_jsonb(no_account),
    'uploads', coalesce((select jsonb_agg(jsonb_build_object('key', storage_key, 'source', substring(storage_key from 8)))
                         from public.ar_files where storage_key like 'legacy/%'), '[]'));
end $$;

