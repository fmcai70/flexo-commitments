-- Step 1 of an upload: checks the rules and reserves a storage path. Step 2 (the app) uploads the file there.
create or replace function public.ar_file_begin(p_kind text, p_parent text, p_name text, p_size bigint, p_as text default null)
returns jsonb language plpgsql volatile security definer set search_path = public as $$
declare
  me public.ar_members := public.ar_actor(p_as);
  ext text := lower(substring(coalesce(p_name, '') from '\.([A-Za-z0-9]+)$'));
  owner text; assignee text;
  f public.ar_files;
begin
  if p_kind not in ('p', 's') or p_parent !~ '^[A-Za-z0-9_-]{1,64}$' then perform public.ar_err('AR400', 'Bad request.'); end if;
  if coalesce(ext, '') not in ('xlsx', 'xlsm', 'xls', 'csv') then
    perform public.ar_err('AR400', 'Only Excel or CSV files (.xlsx, .xlsm, .xls, .csv).');
  end if;
  if p_size > 14680064 then perform public.ar_err('AR400', 'File is over 14 MB. Please reduce it and try again.'); end if;
  if coalesce(p_size, 0) <= 0 then perform public.ar_err('AR400', 'That file is empty.'); end if;
  if p_kind = 'p' then select o.owner into owner from public.ar_projects o where id = p_parent;
  else select s.owner, s.assignee into owner, assignee from public.ar_subplans s where project_id = p_parent; end if;
  if owner is null then perform public.ar_err('AR404', 'That project no longer exists.'); end if;
  if me.role <> 'exec' and me.display_name is distinct from owner and me.display_name is distinct from assignee then
    perform public.ar_err('AR403', 'Only the owner can attach files here.');
  end if;
  insert into public.ar_files (kind, parent_id, file_name, size_bytes, storage_key, uploaded_by, uploaded_by_user)
  values (p_kind, p_parent, left(regexp_replace(p_name, '^.*[\\/]', ''), 255), p_size,
          to_char(now(), 'YYYYMM') || '/' || replace(gen_random_uuid()::text, '-', '') || '.' || ext, me.display_name, auth.uid())
  returning * into f;
  perform public.ar_audit(case when p_kind = 'p' then 'Project' else 'Subplan' end, p_parent, 'Uploaded', me, f.file_name);
  return jsonb_build_object('id', replace(f.id::text, '-', ''), 'key', f.storage_key, 'name', f.file_name, 'size', f.size_bytes,
                            'by', me.display_name, 'at', to_char(now() at time zone 'Asia/Manila', 'YYYY-MM-DD'));
end $$;

create or replace function public.ar_file_key(p_id text, p_as text default null)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare
  me public.ar_members := public.ar_actor(p_as);
  f public.ar_files;
begin
  begin select * into f from public.ar_files where id = p_id::uuid; exception when others then f := null; end;
  if f.id is null then perform public.ar_err('AR404', 'That file is no longer attached.'); end if;
  if not public.ar_can_open_file(f, me) then perform public.ar_err('AR403', 'You can''t open this file.'); end if;
  return jsonb_build_object('key', f.storage_key, 'name', f.file_name);
end $$;

create or replace function public.ar_file_delete(p_id text, p_as text default null)
returns jsonb language plpgsql volatile security definer set search_path = public as $$
declare
  me public.ar_members := public.ar_actor(p_as);
  f public.ar_files;
  owner text;
begin
  begin select * into f from public.ar_files where id = p_id::uuid; exception when others then f := null; end;
  if f.id is null then return jsonb_build_object('key', null); end if;
  if f.kind = 'p' then select o.owner into owner from public.ar_projects o where id = f.parent_id;
  else select s.owner into owner from public.ar_subplans s where project_id = f.parent_id; end if;
