-- ActionRegister (formerly Flexo Commitments): tables, rules and reminders.
--
-- Runs in the shared Flexo Supabase project, next to Flexo Todo. Run it in Supabase → SQL Editor;
-- it is safe to run again after changes. Flexo Todo's supabase/schema.sql must have been run first
-- (it defines profiles, app_access, is_admin() and has_app_access()). Everything here is prefixed ar_.
--
-- Who may do what (same rules as the old on-premise app, CommitmentRules.cs):
--   * Using the app needs 'actionregister' access (app_access) and an active place on the ActionRegister
--     people list (ar_members), or being an ActionRegister admin. People are linked to their Flexo
--     account by email. Projects refer to people by display name, so names can't be renamed.
--   * Everyone on the list sees every project and sub plan.
--   * Executives (role 'exec') may change anything and delete projects.
--   * A new project must be owned or assigned by the person adding it; the owner can't change later.
--     The owner and the person who assigned it may edit it. Helpers (coResp, activity helpers) may
--     only change activities and helperInputs.
--   * Only the project owner creates its sub plan; its owner and assignee edit it.
--   * Admins (ar_members.is_admin, or a Flexo admin) manage the people list and may "view as"
--     anyone; their changes are then checked as that person and the history notes it.
--   * Excel/CSV attachments (14 MB max): executives and "sees all files" people open all of them;
--     others open their own uploads and files on projects / sub plans they own or are assigned.
-- All changes go through the ar_* functions below, which check these rules; the tables themselves
-- can't be written directly by the app.

-- ---------------------------------------------------------------------
-- Tables
-- ---------------------------------------------------------------------
create table if not exists public.ar_members (
  id              bigint generated by default as identity primary key,
  display_name    text not null unique check (length(display_name) between 2 and 100),
  email           text,                       -- links the person to their Flexo account
  user_id         uuid references public.profiles (id) on delete set null,
  department      text,
  role            text not null default 'manager' check (role in ('manager', 'exec')),
  is_admin        boolean not null default false,
  sees_all_files  boolean not null default false,
  is_active       boolean not null default true,
  sort_order      int not null default 0,
  ad_username     text,                       -- from the old Windows sign-in, for reference
  updated_at      timestamptz not null default now()
);
create unique index if not exists ar_members_email_idx on public.ar_members (lower(email)) where email is not null;

create table if not exists public.ar_projects (
  id           text primary key check (id ~ '^[A-Za-z0-9_-]{1,64}$'),
  owner        text not null,
  assigned_by  text,
  plan         text,
  commit_date  text,
  done         boolean not null default false,
  doc          jsonb not null,                -- the whole project as the app sees it
  version      bigint not null default 1,     -- for "someone else just changed this"
  updated_at   timestamptz not null default now(),
  updated_by   text
);

create table if not exists public.ar_subplans (
  project_id  text primary key references public.ar_projects (id) on delete cascade,
  owner       text not null,
  assignee    text not null,
  doc         jsonb not null,
  version     bigint not null default 1,
  updated_at  timestamptz not null default now(),
  updated_by  text
);

create table if not exists public.ar_files (
  id               uuid primary key default gen_random_uuid(),
  kind             text not null check (kind in ('p', 's')),   -- p = project, s = sub plan
  parent_id        text not null,
  file_name        text not null,
  size_bytes       bigint not null,
  storage_key      text not null unique,      -- path in the 'actionregister' storage bucket
  uploaded_by      text not null,             -- display name
  uploaded_by_user uuid references public.profiles (id) on delete set null,
  uploaded_at      timestamptz not null default now()
);
create index if not exists ar_files_parent_idx on public.ar_files (kind, parent_id);

create table if not exists public.ar_audit_log (
  id            bigint generated by default as identity primary key,
  entity_type   text not null,
  entity_id     text not null,
  action        text not null,
  performed_by  uuid references public.profiles (id) on delete set null,
  acting_as     text,
  at            timestamptz not null default now(),
  details       text
);

-- Reminder digests already sent (so nobody gets the same reminder twice).
create table if not exists public.ar_notification_log (
  key      text primary key,
  sent_at  timestamptz not null default now()
);

-- Emails waiting to go out. A Database Webhook on insert calls the ar-email Edge Function,
-- which sends them through Microsoft 365 (see SETUP.md).
create table if not exists public.ar_outbox (
  id          bigint generated by default as identity primary key,
  to_email    text not null,
  subject     text not null,
  body        text not null,
  created_at  timestamptz not null default now()
);

alter table public.ar_members          enable row level security;
alter table public.ar_projects         enable row level security;
alter table public.ar_subplans         enable row level security;
alter table public.ar_files            enable row level security;
alter table public.ar_audit_log        enable row level security;
alter table public.ar_notification_log enable row level security;
alter table public.ar_outbox           enable row level security;
-- No policies: the app reads and writes only through the functions below.
revoke all on public.ar_members, public.ar_projects, public.ar_subplans, public.ar_files, public.ar_audit_log,
  public.ar_notification_log, public.ar_outbox from anon, authenticated;

